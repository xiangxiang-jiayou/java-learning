public class circle_area {
    private static final double PI = 3.14;
    public static void main(String[] args) {
        int r1 = 2;
        double r2 = 3.7;
        double r3 = 5.2;
        System.out.println("圆1的面积为："+ r1*r1*PI);
        System.out.println("圆2的面积为："+ r2*r2*PI);
        System.out.println("圆3的面积为："+ r3*r3*PI);
    }
}
